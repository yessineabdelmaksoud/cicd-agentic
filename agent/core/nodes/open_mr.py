"""
Node — open_mr (Run B)
Opens a GitLab Merge Request from the sandbox branch. MR type (Draft vs
Normal) comes from the OBJECTIVE gate decision (fix.md FIX-6), not the
reviewer's raw confidence. Idempotent: a duplicate /callback for the same
sandbox_pipeline_id is a no-op (fix.md FIX-7).
"""

import structlog
from core.state import AgentState
from services.gitlab_client import get_gitlab_client
from services.state_store import try_claim_mr_opened
from services.metrics import node_duration

log = structlog.get_logger()


async def open_mr(state: AgentState) -> AgentState:
    with node_duration.labels(node="open_mr").time():
        sandbox_pipeline_id = state.get("sandbox_pipeline_id", 0)

        if sandbox_pipeline_id and not try_claim_mr_opened(sandbox_pipeline_id):
            log.info("open_mr.duplicate_callback_skipped", sandbox_pipeline_id=sandbox_pipeline_id)
            return {**state, "outcome": "pass"}

        project_id = state["project_id"]
        sandbox_branch = state["sandbox_branch"]
        target_branch = state["branch"]
        diagnosis = state.get("diagnosis", {})
        gate_decision = state.get("gate_decision", {})

        is_draft = gate_decision.get("mr_type", "draft") != "normal"

        root_cause = diagnosis.get("root_cause", "Build failure")[:80]
        mr_title = f"[AI Fix] {root_cause}"

        description = _build_description(state)

        client = get_gitlab_client()

        try:
            mr = client.create_merge_request(
                project_id=project_id,
                source_branch=sandbox_branch,
                target_branch=target_branch,
                title=mr_title,
                description=description,
                labels=["ai-fix", "automated"],
                draft=is_draft,
            )

            log.info(
                "open_mr.success",
                mr_iid=mr.get("iid", 0),
                title=mr_title,
                draft=is_draft,
                url=mr.get("web_url", ""),
            )
            # mr_opened_total / mr_merged_total are incremented from GitLab's own
            # Merge Request Hook (see api/routes.py /webhook/mr) — that's the
            # authoritative source that the MR really exists and carries our
            # label, rather than trusting this client call alone.

            return {**state, "outcome": "pass"}

        except Exception as e:
            log.error("open_mr.error", error=str(e))
            return {**state, "outcome": "fail", "error_message": str(e)}


def _build_description(state: AgentState) -> str:
    diagnosis = state.get("diagnosis", {})
    patch = state.get("patch_proposal", {})
    verdict = state.get("review_verdict", {})
    gate_decision = state.get("gate_decision", {})

    files_modified = [f.get("path", "?") for f in patch.get("files_to_modify", [])]
    auto = " (rules-engine deterministic fix — no LLM call)" if verdict.get("auto_approved") else ""

    return f"""## 🤖 AI-Generated Fix

**Pipeline:** #{state['pipeline_id']} on branch `{state['branch']}`
**Commit:** `{state['commit_sha'][:8]}`
**Build type:** `{state['build_type']}`

---

### 🔍 Diagnosis{auto}
**Root cause:** {diagnosis.get('root_cause', 'N/A')}
**Fix type:** `{diagnosis.get('fix_type', 'N/A')}`
**Diagnostician confidence:** {diagnosis.get('confidence', 0.0):.0%}

### 🔧 Patch
**Files modified:** {', '.join(f'`{f}`' for f in files_modified) or 'N/A'}
**Explanation:** {patch.get('explanation', 'N/A')}
**Lines changed:** {gate_decision.get('total_changed_lines', '?')}

### ✅ Review & Gate
**Reviewer approved:** {verdict.get('approved')} (confidence {verdict.get('confidence', 0.0):.0%})
**Concerns:** {verdict.get('concerns') or 'None'}
**Objective gate checks:** {gate_decision.get('checks', {})}

### 🧪 Sandbox Validation
The sandbox pipeline on branch `{state['sandbox_branch']}` **passed**.

---
*Generated by AI-CICD-Embedded Agent v5.0 | Review carefully before merging — no auto-merge.*
"""
